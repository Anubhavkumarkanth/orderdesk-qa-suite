"""Generate docs/traceability.md from the TC-xxx docstrings in tests/, so the document cannot drift from the code."""
import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQ = {  # test-case prefix -> requirement IDs it covers (see docs/requirements.md)
    "ORD": "REQ-ORD-001..003", "VAL": "REQ-VAL-001..002", "QTY": "REQ-QTY-001", "STK": "REQ-STK-001",
    "PRC": "REQ-PRC-001..007", "LIF": "REQ-LIF-001..003", "DAT": "REQ-DAT-001..002", "UI": "REQ-UI-001..003",
}
EXTRA = {"TC-VAL-002": "REQ-DAT-003"}  # test case -> requirement it covers beyond its prefix
rows = []
for path in sorted((ROOT / "tests").rglob("test_*.py")):
    for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
        if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
            m = re.match(r"(TC-([A-Z]+)-\d+): (.*)", ast.get_docstring(node) or "")
            if m:
                reqs = ", ".join(filter(None, [REQ[m.group(2)], EXTRA.get(m.group(1))]))
                rows.append((m.group(1), m.group(3), reqs, f"{path.relative_to(ROOT).as_posix()}::{node.name}"))
rows.sort()
out = ["# Traceability: test case -> requirement -> automated test", "",
       "Generated by `scripts/make_traceability.py`. Do not edit by hand.", "",
       "| Test case | What it checks | Requirements | Automated test |", "|---|---|---|---|"]
out += [f"| {a} | {b} | {c} | `{d}` |" for a, b, c, d in rows]
(ROOT / "docs" / "traceability.md").write_text("\n".join(out) + f"\n\n{len(rows)} test cases.\n", encoding="utf-8")
print(len(rows), "test cases")
